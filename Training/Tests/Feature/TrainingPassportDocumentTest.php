it('serves the document to its employee as a PDF attachment and audits the download', function (): void {
    $f = tpdFixture();
    $document = app(TrainingPassportDocumentStore::class)
        ->generate($f['user'], tpdSubject($f['tenantId'], (int) $f['company']->id, $f['employee']));

    $response = tpdDownload($f['user'], (int) $document->id);
    $response->assertOk()
        ->assertHeader('Content-Type', 'application/pdf');
    expect($response->headers->get('Content-Disposition'))->toContain('attachment')
        ->and($response->streamedContent())->toContain('CERT-OWN-EXPIRED');

    $events = TrainingPassportDocumentAudit::query()
        ->forCompany($f['tenantId'], (int) $f['company']->id)
        ->where('document_id', $document->id)
        ->orderBy('id')
        ->pluck('event_type')
        ->all();
    expect($events)->toBe([TrainingPassportDocument::EVENT_GENERATED, TrainingPassportDocument::EVENT_DOWNLOADED]);
    expect(TrainingPassportDocumentAudit::query()->forCompany($f['tenantId'], (int) $f['company']->id)
        ->where('event_type', TrainingPassportDocument::EVENT_DOWNLOADED)->sole()->actor_user_id)->toBe((int) $f['user']->id);
});

