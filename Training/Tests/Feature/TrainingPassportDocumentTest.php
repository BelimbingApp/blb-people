        ->and(MediaAsset::query()->count())->toBe(1);
});

it('purges expired documents: the bytes and asset go, the row and its audit stay', function (): void {
    $f = tpdFixture();
    Carbon::setTestNow('2026-09-07 10:30:00');
    $store = app(TrainingPassportDocumentStore::class);
    $expired = $store->generate($f['user'], tpdSubject($f['tenantId'], (int) $f['company']->id, $f['employee']));
    $asset = $expired->asset;
    Carbon::setTestNow('2026-10-01 10:30:00');
    $kept = $store->generate($f['otherUser'], tpdSubject($f['tenantId'], (int) $f['company']->id, $f['other']));

    Carbon::setTestNow('2026-10-08 00:00:00');
    test()->artisan('people:training-passport:purge', ['--tenant' => $f['tenantId']])
        ->expectsOutputToContain('Purged 1 expired')->assertSuccessful();

    expect($expired->fresh()->media_asset_id)->toBeNull()
        ->and(MediaAsset::query()->whereKey($asset->id)->exists())->toBeFalse()
        ->and(Storage::disk($asset->disk)->exists($asset->storage_key))->toBeFalse()
        ->and($kept->fresh()->media_asset_id)->not->toBeNull()
        ->and(TrainingPassportDocumentAudit::query()->forCompany($f['tenantId'], (int) $f['company']->id)
            ->where('document_id', $expired->id)->count())->toBe(1);
});

